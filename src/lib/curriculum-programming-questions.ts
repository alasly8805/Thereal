export const CURRICULUM_QUESTIONS: readonly CurriculumQuestion[] = [...BASE_QUESTIONS, ...EXTRA_CURRICULUM_QUESTIONS]
  .map((question, index) => ({ question, index }))
  .sort((a, b) => a.question.lessonNumber.localeCompare(b.question.lessonNumber) || a.index - b.index)
  .map(({ question }) => question);

export function getCurriculumQuestion(id: string): CurriculumQuestion | undefined {
  const exact = CURRICULUM_QUESTIONS.find((question) => question.id === id);
  if (exact) return exact;
  const baseId = id.replace(/-gen-\d+$/, "");
  return CURRICULUM_QUESTIONS.find((question) => question.id === baseId);
}

export function getCurriculumQuestionsByChapter(chapter: CurriculumChapter | "all"): CurriculumQuestion[] {
  if (chapter === "all") return [...CURRICULUM_QUESTIONS];
  if (chapter === "python") {
    // Backwards compatibility alias: return data & ai questions
    return CURRICULUM_QUESTIONS.filter((q) => q.chapter === "data" || q.chapter === "ai" || q.chapter === "python");
  }
  return CURRICULUM_QUESTIONS.filter((q) => q.chapter === chapter);
}

/**
 * Generates an expanded set of 100 curriculum practice questions
 * strictly based on the 7 chapters and 23 lessons of the official curriculum.
 */
export function generate100CurriculumQuestions(chapter: CurriculumChapter | "all" = "all"): CurriculumQuestion[] {
  const basePool = getCurriculumQuestionsByChapter(chapter);
  if (basePool.length === 0) return [...CURRICULUM_QUESTIONS];

  const targetCount = 100;
  const result: CurriculumQuestion[] = [];

  // 1. Add all unique base questions first
  const shuffledBase = [...basePool].sort(() => Math.random() - 0.5);
  result.push(...shuffledBase);

  // 2. If already >= 100, return first 100
  if (result.length >= targetCount) {
    return result.slice(0, targetCount);
  }

  // 3. Clone and cycle curriculum variations with fresh IDs until exactly 100
  let cycle = 1;
  while (result.length < targetCount) {
    for (const q of shuffledBase) {
      if (result.length >= targetCount) break;
      result.push({
        ...q,
        id: `${q.id}-gen-${cycle}`,
        question: q.question,
      });
    }
    cycle++;
  }

  return result;
}
